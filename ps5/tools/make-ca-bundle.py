#!/usr/bin/env python3
"""Writes ps5/src/jf/jf_ca_bundle.inc: Mozilla's root certificates (the list the certifi package ships), as one C string.

    python3 ps5/tools/make-ca-bundle.py [path/to/cacert.pem]      (default: the certifi package, pip install certifi)

The list is data under the Mozilla Public License 2.0 (https://www.mozilla.org/MPL/2.0/). Run this again to refresh the
roots; commit the result. The program trusts these roots plus anything in /data/jf-ca.pem.
"""
import hashlib
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
out = os.path.join(root, "ps5", "src", "jf", "jf_ca_bundle.inc")

if len(sys.argv) > 1:
    src = sys.argv[1]
    version = "file " + os.path.basename(src)
else:
    try:
        import certifi
    except ImportError:
        sys.exit("certifi is not installed: pip install certifi (or pass the path of a cacert.pem)")
    src = certifi.where()
    version = "certifi " + getattr(certifi, "__version__", "?")

text = open(src, "r", encoding="utf-8").read()
blocks = re.findall(r"-----BEGIN CERTIFICATE-----\r?\n[A-Za-z0-9+/=\r\n]+?-----END CERTIFICATE-----", text)
if len(blocks) < 100:
    sys.exit("only %d certificates found in %s: not a root list" % (len(blocks), src))
pem = "".join(b.replace("\r", "").strip() + "\n" for b in blocks)

lines = []
lines.append("/* Mozilla's root certificates (%s, %d certificates, sha256 %s).\n"
             " * Generated by ps5/tools/make-ca-bundle.py: do not edit. Data under the Mozilla Public License 2.0. */" %
             (version, len(blocks), hashlib.sha256(pem.encode()).hexdigest()[:16]))
lines.append("static const char kJfCaBundle[] =")
for row in pem.splitlines():
    lines.append('\t"%s\\n"' % row)
lines[-1] += ";"
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote %s: %d certificates, %d bytes" % (out, len(blocks), os.path.getsize(out)))
